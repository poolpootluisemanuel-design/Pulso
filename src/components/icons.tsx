// Iconografía SVG consistente para la navegación (sin emojis).
// Estilo lineal (tipo Feather): trazo currentColor, vista 24×24.
// Todos los iconos comparten el mismo trazo para que la barra se
// vea uniforme en web y en Android.

import type { ReactNode } from 'react'

type IconProps = { className?: string }

function Svg({ className = 'h-6 w-6', children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {children}
    </svg>
  )
}

